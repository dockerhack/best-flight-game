// random.js — seeded RNG. Deterministic: same seed, same world, same frame.
// Gameplay and screenshots both run off this, never Math.random, so a shot
// staged with ?seed=N renders identically every time.

export function mulberry32(seed) {
  let a = seed >>> 0;
  return function next() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function makeRng(seed) {
  const next = mulberry32(seed);
  return {
    next,
    range(a, b) {
      return a + (b - a) * next();
    },
    int(a, b) {
      return Math.floor(a + (b - a + 1) * next());
    },
    pick(arr) {
      return arr[Math.floor(next() * arr.length)];
    },
    // Normal-ish value in [-1, 1] for judging wobble and gusts.
    wobble() {
      return (next() + next() + next() - 1.5) / 1.5;
    },
    // Fisher-Yates shuffle, seeded like everything else.
    shuffle(arr) {
      const a = arr.slice();
      for (let i = a.length - 1; i > 0; i--) {
        const j = Math.floor(next() * (i + 1));
        const t = a[i];
        a[i] = a[j];
        a[j] = t;
      }
      return a;
    },
  };
}
